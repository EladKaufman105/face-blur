import { defineConfig, type Plugin } from 'vite'
import preact from '@preact/preset-vite'
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = dirname(fileURLToPath(import.meta.url))

// Which web app is built (ONIT_CHANNEL): the release (main, the site's root) or the beta
// (develop, under beta/). See src/lib/channel.ts.
const channel = process.env.ONIT_CHANNEL || 'release'
if (channel !== 'release' && channel !== 'beta') throw new Error(`ONIT_CHANNEL must be release or beta, not ${channel}`)

/** The beta's own files: its name, its manifest (a separate installed app), icons with a BETA tag. */
function beta(): Plugin {
  const manifest = () => {
    const m = JSON.parse(readFileSync(join(web, 'public', 'manifest.webmanifest'), 'utf8'))
    return JSON.stringify({ ...m, id: 'onit-beta', name: 'ONIT Beta', short_name: 'ONIT Beta' }, null, 2) + '\n'
  }
  // The landing page (public/home/) can't read the build's constants: it reads this file.
  const homeChannel = "// Generated by vite.config.ts: the beta's settings are kept apart from the release's.\nself.ONIT_STORE = 'onit-beta'\n"
  let outDir = 'dist'
  let build = false
  return {
    name: 'onit-beta',
    configResolved(c) { outDir = resolve(c.root, c.build.outDir); build = c.command === 'build' },
    transformIndexHtml: (html) => html.replace('<title>ONIT</title>', '<title>ONIT Beta</title>').replace('name="apple-mobile-web-app-title" content="ONIT"', 'name="apple-mobile-web-app-title" content="ONIT Beta"'),
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const path = req.url?.split('?')[0]
        const body = path === '/manifest.webmanifest' ? manifest() : path === '/home/channel.js' ? homeChannel : null
        if (body === null) return next()
        res.setHeader('content-type', path!.endsWith('.js') ? 'text/javascript' : 'application/manifest+json')
        res.end(body)
      })
    },
    closeBundle() {
      if (!build) return
      writeFileSync(join(outDir, 'manifest.webmanifest'), manifest())
      writeFileSync(join(outDir, 'home', 'channel.js'), homeChannel)
      const icons = join(web, 'beta', 'icons')
      for (const f of readdirSync(icons)) copyFileSync(join(icons, f), join(outDir, 'icons', f))
    },
  }
}

// Served from GitHub Pages under /face-blur/ (relative base works anywhere).
export default defineConfig({
  base: './',
  plugins: [preact(), ...(channel === 'beta' ? [beta()] : [])],
  define: {
    // The build's number on GitHub Actions (shown in the footer), "dev" locally.
    __BUILD__: JSON.stringify(process.env.GITHUB_RUN_NUMBER ?? 'dev'),
    __CHANNEL__: JSON.stringify(channel),
  },
  worker: { format: 'es' },
  build: { target: 'es2022', chunkSizeWarningLimit: 2000 },
  optimizeDeps: { exclude: ['onnxruntime-web'] },
})
