// The editor as the app's, part three (in English, so the strings' English is checked too):
// - a subtitle merged with the one before it or the one after it, from its properties (one undo step each);
// - a tablet's side panel showing the selected subtitle's properties (text, times, start / end here, split, merge, delete),
//   "Properties" in the top bar when the panel is closed, and the tool panel back when nothing is selected;
// - the blur view: the real blur or outlines only (the blur gone from the picture, an outline drawn), back again;
// - the export sheet's "Output: W×H · fps · about X MB", smaller for a lower resolution and for "saver", not for MP3;
// - a failed export: a message to act on, its technical details folded under it, copied to the clipboard;
// - an error nothing caught: the report dialog with its details, Copy, Close (a cancelled job's AbortError never shows it).
// Run: node tests/parity3.cjs <url> <video with speech> <out dir>
const { chromium } = require('playwright')
const fs = require('fs')
const [, , url, video, out] = process.argv
const SRT = `1\n00:00:01,000 --> 00:00:03,000\nשלום לכולם\n\n2\n00:00:04,000 --> 00:00:06,000\nהיום נדבר\n\n3\n00:00:08,000 --> 00:00:09,000\nתודה רבה\n`

;(async () => {
  fs.mkdirSync(out, { recursive: true })
  fs.writeFileSync(`${out}/a.srt`, SRT)
  const b = await chromium.launch()
  const logs = []
  const fail = (m) => { throw new Error(m) }
  const open = async (viewport, tool = 0) => {
    const ctx = await b.newContext({ viewport, locale: 'en-US' })
    await ctx.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: new URL(url).origin })
    const p = await ctx.newPage()
    p.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`))
    p.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`))
    await p.goto(url)
    await p.waitForTimeout(800)
    const chooser = p.waitForEvent('filechooser')
    await p.click(`.tool >> nth=${tool}`)
    await (await chooser).setFiles(video)
    await p.waitForSelector('.editor .tabs', { timeout: 30000 })
    await p.waitForTimeout(1000)
    return p
  }
  const cues = (p) => p.evaluate(() => [...document.querySelectorAll('.tl-cue')].map((e) => ({ a: Number(e.dataset.a), b: Number(e.dataset.b), text: e.textContent, on: e.classList.contains('on') })))
  const undo = (p) => p.keyboard.press('Control+z')
  try {
    // ---- a subtitle merged with the one before or after it (desktop)
    let p = await open({ width: 1366, height: 860 })
    await p.setInputFiles('.srt-import input', `${out}/a.srt`)
    await p.waitForSelector('.tl-cue')
    await p.waitForTimeout(500)
    if ((await cues(p)).length !== 3) fail('the SRT did not give three subtitles')
    await p.click('.tl-cue >> nth=1')
    await p.waitForSelector('.cue-props .cue-merge-prev')
    if (await p.isDisabled('.cue-merge-prev') || await p.isDisabled('.cue-merge-next')) fail('the middle subtitle cannot merge both ways')
    await p.click('.cue-merge-prev')
    await p.waitForTimeout(300)
    let c = await cues(p)
    if (c.length !== 2 || !/שלום לכולם היום נדבר/.test(c[0].text) || !c[0].on) fail('merge with the previous: ' + JSON.stringify(c))
    if (!(Math.abs(c[0].a - 1) < 0.05 && Math.abs(c[0].b - 6) < 0.05)) fail('the merged times: ' + JSON.stringify(c[0]))
    // The first one has no previous to merge with.
    if (!(await p.isDisabled('.cue-merge-prev'))) fail('the first subtitle offers to merge with a previous one')
    await undo(p)
    await p.waitForTimeout(300)
    if ((await cues(p)).length !== 3) fail('undo of the merge')
    await p.click('.tl-cue >> nth=1')
    await p.waitForSelector('.cue-merge-next')
    await p.click('.cue-merge-next')
    await p.waitForTimeout(300)
    c = await cues(p)
    if (c.length !== 2 || !/היום נדבר תודה רבה/.test(c[1].text) || !c[1].on) fail('merge with the next: ' + JSON.stringify(c))
    if (!(await p.isDisabled('.cue-merge-next'))) fail('the last subtitle offers to merge with a next one')
    await undo(p)
    await p.waitForTimeout(300)
    if ((await cues(p)).length !== 3) fail('undo of the merge with the next')
    await p.screenshot({ path: `${out}/1_merge.png` })

    // ---- the export sheet's size estimate
    await p.keyboard.press('Escape')
    await p.click('.export-bar .btn.primary')
    await p.waitForSelector('.export-sheet')
    await p.waitForSelector('.export-estimate', { timeout: 20000 })
    const est = async () => {
      const s = (await p.textContent('.export-estimate')).replace(/[⁦-⁩]/g, '')
      const m = s.match(/^Output: (\d+)×(\d+) · (\d+) fps · about (\d+(?:\.\d)?) (MB|GB)$/)
      if (!m) fail('the estimate reads: ' + s)
      return { w: +m[1], h: +m[2], fps: +m[3], mb: +m[4] * (m[5] === 'GB' ? 1000 : 1), s }
    }
    const e0 = await est()
    console.log('estimate:', e0.s)
    const quality = p.locator('.export-sheet .seg', { hasText: 'Saver' }).locator('button')
    await quality.nth(0).click()
    const eo = await est()
    // As the source (its own bitrate over its length): about the file's size.
    const srcMb = fs.statSync(video).size / 1e6
    if (eo.mb < srcMb * 0.4 || eo.mb > srcMb * 2.5 + 1) fail(`the estimate as the original (${eo.mb} MB) is far from the source (${srcMb.toFixed(1)} MB)`)
    await quality.nth(2).click()
    const es = await est()
    if (!(es.mb <= eo.mb)) fail(`saver is not smaller: ${es.mb} > ${eo.mb}`)
    const lower = p.locator('.export-size .chip >> nth=1')
    if (await lower.count()) {
      await lower.click()
      const el = await est()
      if (!(el.w * el.h < es.w * es.h) || !(el.mb <= es.mb)) fail('a lower resolution: ' + el.s + ' after ' + es.s)
    }
    await p.click('.export-format button >> nth=1')
    await p.waitForTimeout(200)
    if (await p.$('.export-estimate')) fail('the estimate shows for an MP3')
    await p.click('.export-format button >> nth=0')
    await p.screenshot({ path: `${out}/2_estimate.png` })
    await p.keyboard.press('Escape')

    // ---- an error nothing caught: the report dialog (an AbortError is not one)
    await p.evaluate(() => { Promise.reject(new DOMException('parity3 stopped', 'AbortError')) })
    await p.waitForTimeout(400)
    if (await p.$('.crash-dialog')) fail('a cancelled job showed the report dialog')
    await p.evaluate(() => { setTimeout(() => { throw new Error('parity3 forced crash') }) })
    await p.waitForSelector('.crash-dialog')
    const report = await p.textContent('.crash-text')
    if (!/parity3 forced crash/.test(report) || !/ONIT.*web/.test(report)) fail('the report: ' + report)
    if (!/Copy the details/.test(await p.textContent('.crash-dialog'))) fail('the dialog is not in English')
    await p.click('.crash-copy')
    await p.waitForSelector('.crash-dialog .error-copied')
    const clip = await p.evaluate(() => navigator.clipboard.readText())
    if (!clip.includes('parity3 forced crash')) fail('the clipboard: ' + clip)
    await p.screenshot({ path: `${out}/3_crash.png` })
    await p.click('.crash-close')
    await p.waitForSelector('.crash-dialog', { state: 'detached' })
    await p.context().close()

    // ---- the blur view: a blur by hand, then outlines only, and back
    p = await open({ width: 1366, height: 860 }, 1)
    await p.click('.tabs button[data-g=faces]')
    await p.evaluate(() => { const v = document.querySelector('video'); v.pause(); v.currentTime = 5 })
    await p.waitForTimeout(400)
    await p.click('.add-blur')
    const box = await p.locator('.screen canvas >> nth=0').boundingBox()
    await p.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.4)
    await p.waitForSelector('.ctx-bar .progress', { timeout: 20000 }).catch(() => {})
    await p.waitForFunction(() => !document.querySelector('.ctx-bar .progress'), null, { timeout: 300000 })
    if ((await p.$$('.tl-face')).length !== 1) fail('no blur added')
    await p.keyboard.press('Escape')
    await p.evaluate(() => { const v = document.querySelector('video'); v.pause(); v.currentTime = 5.04 })
    await p.waitForTimeout(600)
    const clipBox = { x: box.x + box.width * 0.4, y: box.y + box.height * 0.3, width: box.width * 0.2, height: box.height * 0.2 }
    const ink = () => p.evaluate(() => { const c = document.querySelectorAll('.view canvas')[1]; const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 3; i < d.length; i += 4) if (d[i] > 0) n++; return n })
    if ((await p.getAttribute('.blur-view', 'aria-pressed')) !== 'true') fail('the blur view does not start on the blur')
    const blurred = await p.screenshot({ clip: clipBox })
    if ((await ink()) !== 0) fail('outlines drawn with the blur view on and nothing selected')
    await p.click('.blur-view')
    await p.waitForTimeout(500)
    if ((await p.getAttribute('.blur-view', 'aria-pressed')) !== 'false') fail('the toggle did not switch')
    const outlined = await p.screenshot({ clip: clipBox })
    if (blurred.equals(outlined)) fail('the picture did not change with outlines only')
    if ((await ink()) < 50) fail('no outline drawn with outlines only')
    await p.screenshot({ path: `${out}/4_outlines.png` })
    await p.click('.blur-view')
    await p.waitForTimeout(500)
    if ((await ink()) !== 0) fail('the outline stayed with the blur back on')
    const again = await p.screenshot({ clip: clipBox })
    if (!again.equals(blurred)) console.log('note: the blurred picture differs a little after the toggle (redraw)')
    // The project's picture (the home screen's) is always the blurred one, outlines or not.
    const readThumb = () => p.evaluate(async () => {
      const name = (await indexedDB.databases()).map((d) => d.name).find((n) => /projects/.test(n))
      const db = await new Promise((res, rej) => { const r = indexedDB.open(name); r.onsuccess = () => res(r.result); r.onerror = rej })
      const all = await new Promise((res) => { const q = db.transaction('meta').objectStore('meta').getAll(); q.onsuccess = () => res(q.result) })
      db.close()
      return all[0]?.thumb ?? null
    })
    const bump = async () => { await p.keyboard.press('Control+z'); await p.waitForTimeout(300); await p.keyboard.press('Control+Shift+z'); await p.waitForTimeout(2500) }
    const thumbDiff = (x, y) => p.evaluate(async ([x, y]) => {
      const px = async (u) => { const i = new Image(); i.src = u; await i.decode(); const c = document.createElement('canvas'); c.width = i.width; c.height = i.height; const g = c.getContext('2d'); g.drawImage(i, 0, 0); return g.getImageData(0, 0, c.width, c.height).data }
      const a = await px(x), b = await px(y); let s = 0; for (let k = 0; k < a.length; k += 4) s += Math.abs(a[k] - b[k]) + Math.abs(a[k + 1] - b[k + 1]) + Math.abs(a[k + 2] - b[k + 2]); return s / (a.length / 4)
    }, [x, y])
    await bump()
    const thumbOn = await readThumb()
    await p.click('.blur-view')
    await p.waitForTimeout(400)
    await bump()
    const thumbOutlines = await readThumb()
    await p.click('.blur-view')
    await p.waitForTimeout(400)
    await bump()
    const thumbAgain = await readThumb()
    if (!thumbOn || !thumbOutlines || !thumbAgain) fail('no project picture saved')
    const dOut = await thumbDiff(thumbOn, thumbOutlines), dAgain = await thumbDiff(thumbOn, thumbAgain)
    console.log('project picture: blur vs outlines', dOut.toFixed(2), 'blur vs blur again', dAgain.toFixed(2))
    if (dOut > Math.max(3, dAgain * 3)) fail(`the project's picture shows the face with outlines on (${dOut.toFixed(2)} against ${dAgain.toFixed(2)})`)
    if ((await p.getAttribute('.blur-view', 'aria-pressed')) !== 'true') fail('the blur view is not back on')
    // A phone with the safe zone's switch too (a 9:16 frame): the top bar still fits (Export keeps only its icon).
    await p.click('.tabs button[data-g=picture]')
    await p.click('.frame-aspect button >> nth=1')
    await p.waitForSelector('.safe-toggle')
    await p.setViewportSize({ width: 393, height: 852 })
    await p.waitForTimeout(600)
    if (await p.$('.panel:not([hidden]) .panel-close')) await p.click('.panel-close')
    const bar = await p.evaluate(() => [...document.querySelectorAll('.top-row button')].filter((e) => e.offsetParent).map((e) => { const r = e.getBoundingClientRect(); return [Math.round(r.left), Math.round(r.right)] }))
    if (!(await p.$('.top-row .blur-view')) || bar.some(([l, r]) => l < -1 || r > 394)) fail('the phone\'s top bar overflows with the blur view and the safe zone: ' + JSON.stringify(bar))
    await p.screenshot({ path: `${out}/4b_phone_bar.png` })
    await p.setViewportSize({ width: 1366, height: 860 })
    await p.waitForTimeout(400)
    await p.click('.tabs button[data-g=picture]')
    await p.click('.frame-aspect button >> nth=0')

    // ---- a failed export: the message, its details folded, copied
    await p.context().route(/export\.worker[^/]*\.js/, (r) => r.fulfill({ contentType: 'text/javascript', body: `self.onmessage = () => self.postMessage({ type: 'error', code: 'encoder', message: 'parity3 forced failure' })` }))
    await p.click('.export-bar .btn.primary')
    await p.waitForSelector('.export-go')
    await p.click('.export-go')
    await p.waitForSelector('.card.error', { timeout: 30000 })
    const msg = await p.textContent('.export-error')
    if (!/couldn't save at this resolution/.test(msg)) fail('the export failure says: ' + msg)
    if (await p.$('.error-details-text')) fail('the details are not folded')
    await p.click('.error-details-toggle')
    const det = await p.textContent('.error-details-text')
    if (!/encoder/.test(det) || !/parity3 forced failure/.test(det)) fail('the details: ' + det)
    await p.click('.error-copy')
    await p.waitForSelector('.error-copied')
    if (!(await p.evaluate(() => navigator.clipboard.readText())).includes('parity3 forced failure')) fail('the details were not copied')
    await p.screenshot({ path: `${out}/5_export_error.png` })
    await p.context().close()

    // ---- a tablet: the selected subtitle's properties in the side panel
    p = await open({ width: 1024, height: 768 })
    if (!/\btablet\b/.test(await p.getAttribute('.editor', 'class'))) fail('not the tablet layout')
    await p.setInputFiles('.srt-import input', `${out}/a.srt`)
    await p.waitForSelector('.tl-cue')
    await p.waitForTimeout(500)
    await p.click('.tl-cue >> nth=1')
    await p.waitForSelector('.side .cue-side')
    if (!(await p.isHidden('.side > .panel'))) fail('the tool panel shows beside the subtitle\'s properties')
    if (await p.$('.player .cue-props')) fail('the properties are under the bar too')
    if (await p.$('.cue-bar .cue-edit')) fail('"Edit text" in the bar opens nothing with the side panel open')
    const sideText = await p.textContent('.cue-side')
    for (const w of ['Text', 'Start here', 'End here', 'Split here', 'Merge with', 'Delete']) if (!sideText.includes(w)) fail(`no "${w}" in the side panel: ` + sideText)
    if ((await p.inputValue('.cue-side .cue-prop-text')) !== 'היום נדבר') fail('the side panel is not the selected subtitle')
    await p.fill('.cue-side .cue-prop-text', 'היום נדבר הרבה')
    await p.waitForTimeout(200)
    if (!/היום נדבר הרבה/.test((await cues(p))[1].text)) fail('the text typed in the side panel is not the subtitle\'s')
    await p.evaluate(() => { const v = document.querySelector('video'); v.pause(); v.currentTime = 4.5 })
    await p.waitForTimeout(300)
    await p.click('.cue-side-start')
    await p.waitForTimeout(200)
    if (Math.abs((await cues(p))[1].a - 4.5) > 0.06) fail('Start here in the side panel: ' + JSON.stringify((await cues(p))[1]))
    await p.screenshot({ path: `${out}/6_tablet_props.png` })
    // Esc in its text field closes it; a group picked in the rail is shown (the subtitle no longer selected).
    await p.focus('.cue-side .cue-prop-text')
    await p.keyboard.press('Escape')
    await p.waitForSelector('.cue-side', { state: 'detached' })
    await p.click('.tl-cue >> nth=1')
    await p.waitForSelector('.side .cue-side')
    await p.click('.tabs button[data-g=sound]')
    await p.waitForSelector('.cue-side', { state: 'detached' })
    if (await p.isHidden('.side > .panel')) fail('the group picked with a subtitle selected is not shown')
    await p.click('.tabs button[data-g=subs]')
    await p.click('.tl-cue >> nth=1')
    await p.waitForSelector('.side .cue-side')
    const m = await p.evaluate(() => ({ sideways: document.documentElement.scrollWidth > innerWidth, scroll: document.documentElement.scrollHeight - document.documentElement.clientHeight }))
    if (m.sideways || m.scroll > 1) fail('the tablet page scrolls with the properties: ' + JSON.stringify(m))
    // The panel closed: "Properties" in the top bar opens it again.
    await p.click('.cue-side .icon-btn')
    await p.waitForSelector('.cue-side', { state: 'detached' })
    if (await p.isHidden('.side > .panel')) fail('the tool panel did not come back with nothing selected')
    await p.click('.panel-close')
    await p.click('.tl-cue >> nth=1')
    await p.waitForSelector('.props-open')
    if (await p.$('.cue-side')) fail('the side panel opened by itself')
    await p.click('.props-open')
    await p.waitForSelector('.side .cue-side')
    await p.click('.cue-side-delete')
    await p.waitForTimeout(300)
    if ((await cues(p)).length !== 2 || (await p.$('.cue-side'))) fail('Delete in the side panel')
    if (logs.some((l) => l.startsWith('[pageerror]') && !/parity3 (forced|stopped)/.test(l))) fail('page errors: ' + logs.filter((l) => l.startsWith('[pageerror]')).join('\n'))
    console.log('PASS')
  } catch (e) {
    console.error('FAIL', e.message)
    fs.writeFileSync(`${out}/log.txt`, logs.join('\n'))
    process.exitCode = 1
  } finally {
    await b.close()
  }
})()
