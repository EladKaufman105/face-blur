// The editor's keyboard: groups by number, play / pause, undo and redo of a placed sound.
const { chromium } = require('playwright')
const [, , url, video, out] = process.argv
;(async () => {
  const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] })
  const p = await (await b.newContext({ viewport: { width: 1366, height: 860 }, locale: 'he-IL' })).newPage()
  try {
    await p.goto(url)
    await p.waitForTimeout(1000)
    const chooser = p.waitForEvent('filechooser')
    await p.click('.tool >> nth=1')
    await (await chooser).setFiles(video)
    await p.waitForSelector('.editor .tabs', { timeout: 30000 })
    await p.waitForTimeout(1500)
    const selected = () => p.evaluate(() => [...document.querySelectorAll('.tabs button')].findIndex((x) => x.classList.contains('on')))
    await p.keyboard.press('5'); if ((await selected()) !== 4) throw new Error('key 5 -> ' + (await selected()))
    await p.keyboard.press('3'); if ((await selected()) !== 2) throw new Error('key 3 -> ' + (await selected()))
    // The sound group, for the sound placed below.
    await p.keyboard.press('4'); if ((await selected()) !== 3) throw new Error('key 4 -> ' + (await selected()))
    await p.keyboard.press('Space'); await p.waitForTimeout(800)
    const playing = await p.evaluate(() => !document.querySelector('video').paused)
    await p.keyboard.press('k'); await p.waitForTimeout(300)
    const paused = await p.evaluate(() => document.querySelector('video').paused)
    console.log('space plays', playing, 'k pauses', paused)
    if (!playing || !paused) throw new Error('play / pause keys')
    await p.click('.sound .name >> nth=0')
    await p.waitForSelector('.tl-sound', { timeout: 5000 })
    await p.mouse.click(5, 5)
    await p.keyboard.press('Control+z'); await p.waitForTimeout(400)
    const afterUndo = await p.evaluate(() => document.querySelectorAll('.tl-sound').length)
    await p.keyboard.press('Control+Shift+z'); await p.waitForTimeout(400)
    const afterRedo = await p.evaluate(() => document.querySelectorAll('.tl-sound').length)
    console.log('sounds after undo', afterUndo, 'after redo', afterRedo)
    if (afterUndo !== 0 || afterRedo !== 1) throw new Error('undo / redo')
    const t0 = await p.evaluate(() => document.querySelector('video').currentTime)
    await p.keyboard.press('ArrowRight'); await p.waitForTimeout(300)
    const t1 = await p.evaluate(() => document.querySelector('video').currentTime)
    console.log('frame step', (t1 - t0).toFixed(3))
    if (!(t1 > t0)) throw new Error('arrow step')
    await p.screenshot({ path: out })
    console.log('PASS')
  } finally { await b.close() }
})().catch((e) => { console.error('FAIL', e.message); process.exit(1) })
