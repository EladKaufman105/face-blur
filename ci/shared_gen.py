#!/usr/bin/env python3
"""Generates plain Kotlin and TypeScript constants from the definitions in shared/ (see
docs/shared-code.md). The app and the web app read the generated files, never the JSON: nothing is
parsed at run time, and each value compiles exactly as the literal it replaced (Kotlin `const val`,
inlined where it is used; TypeScript `export const`, a module-level var: about +106 B gzip, no
runtime cost).

    python3 ci/shared_gen.py                 writes app/.../gen/*.kt and web/src/gen/*.ts
    python3 ci/shared_gen.py --target ts     only the TypeScript (the web build runs this)
    python3 ci/shared_gen.py --check         writes nothing; exits 1 if a generated file is stale,
                                             missing, edited by hand, or not made by this script

The generated files are committed. A file is written only when its content changes, so builds stay
incremental. Python 3 standard library only.

Number literals are copied from the JSON as they are written there ("0.40" stays 0.40, 0.40f in
Kotlin), so a value moved into shared/ keeps the exact text it had in the code.
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
KT_DIR = ROOT / "app/src/main/java/com/elad/faceblur/gen"
TS_DIR = ROOT / "web/src/gen"
KT_PACKAGE = "com.elad.faceblur.gen"

NAME_RE = re.compile(r"^[A-Z][A-Z0-9]*(_[A-Z0-9]+)*$")
NUM_RE = re.compile(r"^-?(0|[1-9][0-9]*)(\.[0-9]+)?$")
INT_RE = re.compile(r"^-?(0|[1-9][0-9]*)$")


class Lit(str):
    """A JSON number, kept as the text it was written as."""


class SpecError(Exception):
    pass


def load(rel):
    path = ROOT / rel
    try:
        return json.loads(path.read_text(encoding="utf-8"), parse_float=Lit, parse_int=Lit)
    except FileNotFoundError:
        raise SpecError(f"{rel}: not found")
    except json.JSONDecodeError as e:
        raise SpecError(f"{rel}: not valid JSON: {e}")


def header(rel):
    return f"// GENERATED by ci/shared_gen.py from {rel}. Do not edit.\n"


def kt_doc(text, indent=""):
    return f"{indent}/** {text} */\n" if text else ""


def ts_doc(text):
    return f"/** {text} */\n" if text else ""


def check_text(rel, what, s):
    if not isinstance(s, str) or isinstance(s, Lit):
        raise SpecError(f"{rel}: {what} must be a string")
    if "*/" in s or "\n" in s:
        raise SpecError(f"{rel}: {what} has '*/' or a line break")
    return s


# A constant: {"name", "type": "float" | "int", "value", "doc"?}. The value is a number, or
# {"num": a, "den": b} for a / b (kept as the division the code had, folded by the compilers).
class Const:
    def __init__(self, rel, name, type_, value, doc=""):
        if not isinstance(name, str) or not NAME_RE.match(name):
            raise SpecError(f"{rel}: '{name}' is not an UPPER_SNAKE name")
        if type_ not in ("float", "int"):
            raise SpecError(f"{rel}: {name}: type must be float or int, not {type_!r}")
        self.name, self.type, self.doc = name, type_, check_text(rel, f"{name}'s doc", doc) if doc else ""
        if isinstance(value, Lit):
            self.parts = [self.num(rel, value)]
        elif isinstance(value, dict) and set(value) == {"num", "den"}:
            if type_ != "float":
                raise SpecError(f"{rel}: {name}: a fraction must be a float")
            self.parts = [self.num(rel, value["num"]), self.num(rel, value["den"])]
            if float(self.parts[1]) == 0:
                raise SpecError(f"{rel}: {name}: divides by 0")
        else:
            raise SpecError(f"{rel}: {name}: the value must be a number or {{num, den}}")

    def num(self, rel, v):
        if not isinstance(v, Lit) or not NUM_RE.match(v):
            raise SpecError(f"{rel}: {self.name}: {v!r} is not a plain decimal number")
        if self.type == "int" and not INT_RE.match(v):
            raise SpecError(f"{rel}: {self.name}: an int can't be {v}")
        return str(v)

    def kt(self):
        if self.type == "int":
            return self.parts[0]
        return " / ".join(p + "f" for p in self.parts)

    def ts(self):
        """A fraction as its value: the double JavaScript computes for a / b (Python's division of two
        doubles is the same IEEE operation, and repr() reads back as that double), so the bundler
        can inline it like any literal. The division stays in a comment."""
        if len(self.parts) == 1:
            return self.parts[0]
        return f"{float(self.parts[0]) / float(self.parts[1])!r} // {self.parts[0]} / {self.parts[1]}"


def const_list(rel, items):
    """[{"section": text} | const]: the constants, and the section comments between them."""
    if not isinstance(items, list):
        raise SpecError(f"{rel}: 'consts' must be a list")
    out, seen = [], set()
    for it in items:
        if not isinstance(it, dict):
            raise SpecError(f"{rel}: each entry of 'consts' is an object")
        if set(it) == {"section"}:
            out.append(check_text(rel, "a section", it["section"]))
            continue
        extra = set(it) - {"name", "type", "value", "doc"}
        if extra or not {"name", "type", "value"} <= set(it):
            raise SpecError(f"{rel}: {it.get('name', it)}: keys must be name, type, value and doc (optional), not {sorted(it)}")
        c = Const(rel, it["name"], it["type"], it["value"], it.get("doc", ""))
        if c.name in seen:
            raise SpecError(f"{rel}: {c.name} is there twice")
        seen.add(c.name)
        out.append(c)
    return out


def emit_consts(rel, about, obj, entries):
    """One Kotlin object of `const val`s and one TypeScript module of `export const`s."""
    kt = [header(rel), f"package {KT_PACKAGE}\n\n", kt_doc(about), f"object {obj} {{\n"]
    ts = [header(rel), ts_doc(about) + "\n" if about else ""]
    first = True
    for e in entries:
        if isinstance(e, str):
            kt.append(("" if first else "\n") + f"    // {e}\n")
            ts.append(("" if first else "\n") + f"// {e}\n")
        else:
            kt.append(kt_doc(e.doc, "    ") + f"    const val {e.name} = {e.kt()}\n")
            ts.append(ts_doc(e.doc) + f"export const {e.name} = {e.ts()}\n")
        first = False
    kt.append("}\n")
    return "".join(kt), "".join(ts)


def keys_exactly(rel, d, required, optional=()):
    if not isinstance(d, dict):
        raise SpecError(f"{rel}: expected an object")
    missing = set(required) - set(d)
    extra = set(d) - set(required) - set(optional)
    if missing or extra:
        raise SpecError(f"{rel}: keys {sorted(required)} (and optional {sorted(optional)}) expected; missing {sorted(missing)}, unknown {sorted(extra)}")


def gen_detect():
    rel = "shared/detect/detect.json"
    d = load(rel)
    keys_exactly(rel, d, ["about", "consts"])
    kt, ts = emit_consts(rel, check_text(rel, "about", d["about"]), "DetectConst", const_list(rel, d["consts"]))
    return {"kotlin": {"DetectConst.kt": kt}, "ts": {"detect.ts": ts}}


def gen_bleep():
    rel = "shared/audio/bleep.json"
    d = load(rel)
    keys_exactly(rel, d, ["about", "consts"])
    kt, ts = emit_consts(rel, check_text(rel, "about", d["about"]), "BleepConst", const_list(rel, d["consts"]))
    return {"kotlin": {"BleepConst.kt": kt}, "ts": {"bleep.ts": ts}}


def gen_safezones():
    """Each platform's four margins, as <ID>_TOP, _BOTTOM, _LEFT, _RIGHT. {"px": n} is n pixels of
    the measuring frame: top and bottom over its height, left and right over its width."""
    rel = "shared/catalog/safezones.json"
    d = load(rel)
    keys_exactly(rel, d, ["about", "frame", "platforms"])
    keys_exactly(rel + " frame", d["frame"], ["width", "height"])
    size = {"top": d["frame"]["height"], "bottom": d["frame"]["height"], "left": d["frame"]["width"], "right": d["frame"]["width"]}
    entries, ids = [], set()
    for p in d["platforms"]:
        keys_exactly(rel + " platform", p, ["id", "top", "bottom", "left", "right"], ["doc"])
        pid = p["id"]
        if not isinstance(pid, str) or not re.match(r"^[a-z][a-z0-9]*$", pid) or pid in ids:
            raise SpecError(f"{rel}: platform id {pid!r} must be lowercase letters and digits, and new")
        ids.add(pid)
        entries.append(check_text(rel, "a platform's doc", p.get("doc", pid)))
        for side in ("top", "bottom", "left", "right"):
            v = p[side]
            if isinstance(v, dict):
                keys_exactly(f"{rel} {pid}.{side}", v, ["px"])
                v = {"num": v["px"], "den": size[side]}
            entries.append(Const(rel, f"{pid.upper()}_{side.upper()}", "float", v))
    kt, ts = emit_consts(rel, check_text(rel, "about", d["about"]), "SafeZones", entries)
    return {"kotlin": {"SafeZones.kt": kt}, "ts": {"safezones.ts": ts}}


GENERATORS = [gen_detect, gen_bleep, gen_safezones]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--target", choices=["kotlin", "ts", "all"], default="all")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if a generated file differs")
    a = ap.parse_args()
    targets = ["kotlin", "ts"] if a.target == "all" else [a.target]
    dirs = {"kotlin": (KT_DIR, ".kt"), "ts": (TS_DIR, ".ts")}

    want = {}
    try:
        for g in GENERATORS:
            out = g()
            for t in targets:
                for name, text in out[t].items():
                    want[dirs[t][0] / name] = text
    except SpecError as e:
        print(f"shared_gen: {e}", file=sys.stderr)
        return 1

    problems, written = [], []
    for path, text in sorted(want.items()):
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        rel = path.relative_to(ROOT)
        if a.check:
            problems.append(f"{rel}: {'missing' if old is None else 'stale or edited by hand'}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            written.append(str(rel))
    # A file in gen/ the script doesn't make: a hand-written one, or one whose JSON was removed.
    for t in targets:
        d, ext = dirs[t]
        if d.is_dir():
            for f in sorted(d.iterdir()):
                if f.suffix in (".kt", ".ts") and f not in want:
                    problems.append(f"{f.relative_to(ROOT)}: not made by ci/shared_gen.py (remove it, or its definitions are gone from shared/)")
    for w in written:
        print(f"shared_gen: wrote {w}")
    if problems:
        for p in problems:
            print(f"shared_gen: {p}", file=sys.stderr)
        if a.check:
            print("shared_gen: run `python3 ci/shared_gen.py` and commit the result. Edit shared/*.json, never the generated files.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
