#!/usr/bin/env python3
"""Model and library licence data (see THIRD-PARTY-NOTICES.md).

    python3 ci/licences_check.py            checks; exits 1 on a problem or a stale THIRD-PARTY-NOTICES.md
    python3 ci/licences_check.py --write    rewrites THIRD-PARTY-NOTICES.md from the data

The data: every file of app/src/main/assets/model-registry.json has title, licence, copyright, source,
licenceFile and requiresAcceptance; shared/assets/licences/components.json lists the libraries, fonts and
other models. A licenceFile is a path inside the assets: licences/<name>.txt (shared/assets/licences, packaged
into the APK and copied by web/scripts/copy-assets.mjs) or fonts/licenses/<name>.txt (the fonts' own files).
THIRD-PARTY-NOTICES.md is generated from the same data, so it can't drift. Python 3 standard library only."""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "app/src/main/assets/model-registry.json"
COMPONENTS = ROOT / "shared/assets/licences/components.json"
NOTICES = ROOT / "THIRD-PARTY-NOTICES.md"
TEXT_ROOTS = [ROOT / "shared/assets", ROOT / "app/src/main/assets"]
FIELDS = ("title", "licence", "copyright", "source", "licenceFile")


def text_exists(rel: str) -> bool:
    return any((r / rel).is_file() for r in TEXT_ROOTS)


def load():
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    comps = json.loads(COMPONENTS.read_text(encoding="utf-8"))["components"]
    return reg, comps


def problems(reg, comps):
    out = []
    for p in reg["packs"]:
        if not isinstance(p.get("licenceVersion"), int) or p["licenceVersion"] < 1:
            out.append(f"pack {p['id']}: licenceVersion must be an integer >= 1")
        for f in p["files"]:
            for k in FIELDS:
                if not f.get(k):
                    out.append(f"{f['name']}: no {k}")
            if not isinstance(f.get("requiresAcceptance"), bool):
                out.append(f"{f['name']}: requiresAcceptance must be true or false")
            if f.get("licenceFile") and not text_exists(f["licenceFile"]):
                out.append(f"{f['name']}: licence file {f['licenceFile']} not found")
    seen = set()
    for c in comps:
        if c["id"] in seen:
            out.append(f"component {c['id']} twice")
        seen.add(c["id"])
        for k in ("name", "licence", "kind"):
            if not c.get(k):
                out.append(f"component {c['id']}: no {k}")
        if c.get("licenceFile") and not text_exists(c["licenceFile"]):
            out.append(f"component {c['id']}: licence file {c['licenceFile']} not found")
        if not c.get("licenceFile") and not c.get("unverified"):
            out.append(f"component {c['id']}: no licence file and no 'unverified' reason")
    return out


def render(reg, comps):
    L = [
        "# Third-party notices",
        "",
        "ONIT is built on the models, libraries and fonts below. Each is used under its own licence; the full",
        "texts are in [`shared/assets/licences/`](shared/assets/licences) (and `app/src/main/assets/fonts/licenses/`",
        "for the fonts), packaged in the app and served by the web app, and shown in its \"Open-source licences\" screen.",
        "This file is generated by `python3 ci/licences_check.py --write` from",
        "`app/src/main/assets/model-registry.json` and `shared/assets/licences/components.json`; edit those.",
        "",
        "ONIT's own licence is not covered here.",
        "",
        "## Models (downloaded on demand)",
        "",
    ]
    for p in reg["packs"]:
        L.append(f"### Pack `{p['id']}` ({p['feature']})")
        L.append("")
        for f in p["files"]:
            L.append(f"- **{f['title']}** (`{f['name']}`): {f['licence']}. {f['copyright']}. Source: <{f['source']}>."
                     + (" Accepting the terms is required before the download." if f["requiresAcceptance"] else ""))
            if f.get("note"):
                L.append(f"  - {f['note']}")
            if f.get("unverified"):
                L.append(f"  - Not fully verified: {f['unverified']}")
        L.append("")
    for kind, title in (("model", "Other models"), ("library", "Libraries"), ("font", "Fonts")):
        items = [c for c in comps if c["kind"] == kind]
        if not items:
            continue
        L += [f"## {title}", ""]
        for c in items:
            src = f" Source: <{c['source']}>." if c.get("source") else ""
            L.append(f"- **{c['name']}**: {c['licence']}. {c['copyright']}.{src}")
            if c.get("note"):
                L.append(f"  - {c['note']}")
            if c.get("unverified"):
                L.append(f"  - Not fully verified: {c['unverified']}")
        L.append("")
    return "\n".join(L).rstrip() + "\n"


def main():
    reg, comps = load()
    bad = problems(reg, comps)
    for b in bad:
        print("licences:", b)
    want = render(reg, comps)
    if "--write" in sys.argv:
        NOTICES.write_text(want, encoding="utf-8")
        print("wrote", NOTICES.name)
    elif not NOTICES.is_file() or NOTICES.read_text(encoding="utf-8") != want:
        print("licences: THIRD-PARTY-NOTICES.md is stale: run python3 ci/licences_check.py --write")
        bad.append("stale")
    print(f"licences: {sum(len(p['files']) for p in reg['packs'])} model files, {len(comps)} components, {len(bad)} problems")
    sys.exit(1 if bad else 0)


main()
